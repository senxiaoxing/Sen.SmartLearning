/**
 * @file 宠物成长曲线表 —— 每个年级各一条，决定「练多少能满级」
 * @layer domain  纯数据，无副作用
 * @see design/06-宠物系统.md
 * @see design/08-年级分区与内容扩展.md §5.1  为什么曲线必须按年级配
 *
 * ## 为什么曲线不能一套走天下
 *
 * 六年级的内容量比一年级大得多。用同一条曲线，孩子很可能**学到半学期就满级，
 * 剩下半年宠物毫无反应**——那正是 CLAUDE.md 宠物红线第 8 条要守住的另一端。
 *
 * 反过来把曲线拉长到六年级的量，一年级的孩子第一轮就升不了级了。
 * 两端是同一条约束的两面，只能靠一年级一条曲线各自校准。
 *
 * ⚠️ **加年级 = 加一条校准过的曲线**，不是复制一条了事。
 * `growth.test.ts` 会对每个「已经有内容」的年级跑两端校验，没校准会直接红。
 */

import type { GradeLevel } from '@/domain/types'

/** 最高等级 */
export const MAX_LEVEL = 12

/** 形态总数。6 个形态 × 2 级 = 12 级 */
export const STAGE_COUNT = 6

/**
 * 一年级曲线。索引即等级（`[2]` 是升到 2 级所需的**累计**经验）。
 *
 * 同时满足两个目标：
 *
 * **① 开头极快** —— 一轮 10 题全对约 25 exp，
 * 因此第一轮必到 2 级、第二轮就能看到第一次形态变化（3 级）。
 * 孩子首次使用若看不到变化，养成系统对她就只是个不动的图标。
 *
 * **② 满级 ≈ 学完一个年级** —— 一年级数学 47 个知识点、
 * 平均每点 30 题，合计约 1400 题 ≈ 140 轮。满级定在 3000 exp
 * （约 120 轮全对）与之匹配，学完一年正好把宠物养到最终形态。
 */
const G1_CURVE: readonly number[] = [
  0, // Lv1 起始
  0, // Lv1   🥚 蛋
  15, // Lv2  ⭐ 第一轮就能到
  45, // Lv3  🐣 破壳，形态变化（第二轮）
  100, // Lv4
  190, // Lv5 🐧 幼体
  320, // Lv6
  500, // Lv7 🧣 学徒
  750, // Lv8
  1080, // Lv9 🎒 高手
  1500, // Lv10
  2100, // Lv11 👑 最终形态
  3000, // Lv12 满级 ≈ 学完一个年级
]

/**
 * 各年级的成长曲线。
 *
 * ⚠️ **G2~G6 目前是 G1 的占位副本，尚未校准**——那几个年级还没有任何内容，
 * 此刻填任何数字都是猜。等某个年级的知识点做出来，`growth.test.ts` 的
 * 「有内容的年级必须有自己校准过的曲线」会立刻变红，
 * 那时再按该年级的实际题量把这一条替换掉。
 *
 * 刻意留成会红的占位，而不是编一套公式蒙混过去：
 * 曲线偏了在 iPad 上完全看不出来，只会表现为「宠物好久没动静了」，
 * 而那时孩子已经失去兴趣了。
 */
export const LEVEL_CURVES: Record<GradeLevel, readonly number[]> = {
  G1: G1_CURVE,
  G2: G1_CURVE,
  G3: G1_CURVE,
  G4: G1_CURVE,
  G5: G1_CURVE,
  G6: G1_CURVE,
}

/**
 * 取某个年级的曲线。
 *
 * @param gradeLevel - 宠物所属年级，来自 `PetState.gradeLevel`
 * @returns 该年级的累计经验阈值表，索引即等级
 *
 * @example
 * curveOf('G1')[MAX_LEVEL]   // 3000 —— 一年级满级所需经验
 */
export function curveOf(gradeLevel: GradeLevel): readonly number[] {
  return LEVEL_CURVES[gradeLevel]
}
