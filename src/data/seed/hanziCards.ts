/**
 * @file 识字 300 —— 一年级要认的 300 个字，分 3 辑 × 10 组
 * @layer data  静态内容，随 App 版本内置
 * @see src/domain/hanzi.ts  类型与 key 规则（朗读文本怎么拼在那边）
 * @see src/features/chinese/HanziWall.tsx  这面墙
 *
 * ## 为什么分辑
 *
 * 原来是 100 字一条长滚动。她把这 100 个全认下来之后要加字，
 * 如果继续往后接，新字会埋在滚了三屏之后的地方——**她永远看不到新内容**，
 * 而看到的永远是已经会了的那一百个。那正是「像幼儿园小朋友做的题目」
 * 那句话的另一种形态（见 CLAUDE.md 产品红线）。
 *
 * 分辑之后每一辑仍是 100 字 / 10 组，滚动长度不变，
 * 而「第二辑」「第三辑」这两个按钮本身就是「这里有你没见过的字」的信号。
 *
 * ⚠️ **辑的顺序与内容都不要重排**。她记的是「小动物在第一辑最后」这种位置，
 * 与 `PlayEntries` 的入口顺序写死是同一个道理：新内容只能**往后加辑**。
 *
 * ## 选字依据
 *
 * 第一辑取自统编版语文一年级上册的识字课顺序（识字 1「天地人」→ 2「一二三四五上下」
 * → 3「口耳目手足站坐」→ 4「日月水火山石田禾」→ 5「对韵歌」），
 * 并按《义务教育语文课程标准》附录「识字、写字教学基本字表」的原则补足到 100：
 * **构形简单、重现率高、多数能作为其他字的结构成分**。
 *
 * 第二、三辑覆盖一上剩余部分与一下的常用字，同样按基本字表的原则筛，
 * 但**分组一律按孩子能指得出来的东西**，不按课次——这一页是先于入学玩的，
 * 按分课对还没上学的孩子没有意义，按「这些都是我家里人」「这些能吃」才有。
 *
 * 两辑的难度差别不在字的笔画，而在**能不能画出来**：第二辑几乎全是名词与动作
 * （吃穿住行、上学、动物），第三辑开始出现方位、虚词、心情这些只能靠听和用的字。
 *
 * ## ⚠️ 组词不是装饰，是朗读的一部分
 *
 * 每个字念出来是「天。蓝天的天。」——组词嵌在句子中间。所以 `word` 必须：
 *
 * 1. **能锁死多音字的读音** ——「地」单念可能读成助词 de，
 *    放进「大地的地」就只能是 dì。多音字在后两辑里成片出现，
 *    每一个都是靠组词摁住的：
 *    「自行车的行」xíng（不是 háng）·「学校的校」xiào（不是 jiào）·
 *    「给你的给」gěi（不是 jǐ）·「一只的只」zhī（不是 zhǐ）·
 *    「快乐的乐」lè（不是 yuè）·「没有的没」méi（不是 mò）·
 *    「不要的要」yào（不是 yāo）·「中间的中」zhōng（不是 zhòng）·
 *    「中间的间」jiān（不是 jiàn）·「天空的空」kōng（不是 kòng）·
 *    「钥匙的钥」yào（不是 yuè）。
 *    这些字如果组词换成别的，读音就可能翻车，而屏幕上一切正常。
 * 2. **孩子听得懂** —— 组词里的另一个字要么已在这 300 个里，要么是她天天听的词。
 *
 * ⛔ **轻声字不进这张表**：「的」「了」「们」「子」「吗」这些没有声调，
 *    而卡片顶部要显示带调拼音（由 hanziCards.test.ts 强制校验）。
 *    它们该在句子里学，不该做成单字卡。
 *
 * ## emoji 宁缺毋滥
 *
 * 与英语词表同一条规矩（见 englishWords.ts 文件头）：**认不出的图会把认字变成猜谜**。
 * 「大」「多」「来」「去」这类字没有干净的图，一律留空——
 * 卡片只显示字、拼音和组词，那比一张要猜的图干净。
 *
 * 第三辑留空的比例明显更高（方位、虚词整组几乎全空），这是**内容本身的性质**，
 * 不是没配完。「前」「后」「里」「外」真的画不出来，硬配一张图只会让她背错。
 *
 * ⚠️ 还有一类留空是为了**躲开视觉撞车**：「脸」不用 😊，因为「头」已经是 🙂，
 * 两张笑脸摆在同一面墙上，孩子分不出那是两个字还是一个字。
 * 同图撞车由 hanziCards.test.ts 拦，形近撞车拦不住，只能在挑图时想清楚。
 */

import type { HanziCard } from '@/domain/hanzi'

/** 一组识字卡 */
export interface HanziGroup {
  id: string
  /** 组名，给家长看的标签。孩子认的是这一组的图标与字本身 */
  name: string
  emoji: string
  cards: readonly HanziCard[]
}

/**
 * 一辑 = 100 字 = 10 组。墙顶的分辑按钮一个对应一个。
 *
 * ⚠️ 孩子不识字，按钮上「第二辑」三个字她读不出来，
 * **真正起作用的是 `badge` 那个数字**——1️⃣2️⃣3️⃣ 在第一辑第二组就学过，
 * 而且首页与数学题里天天见。`name` 是给家长看的。
 */
export interface HanziVolume {
  id: string
  /** 「第一辑」这类序号标签，家长看的 */
  name: string
  /** ⭐ 孩子真正认的东西：1️⃣2️⃣3️⃣ */
  badge: string
  /** 这一辑装了什么，家长看的一句话 */
  hint: string
  groups: readonly HanziGroup[]
}

/** 组内一个字的原始声明。`groupId` 由 {@link HANZI_VOLUMES} 组装时补上 */
type CardSpec = Omit<HanziCard, 'groupId'>

/** 一组的原始声明。`cards` 里的 `groupId` 同样由组装时补上 */
interface GroupSpec {
  id: string
  name: string
  emoji: string
  cards: readonly CardSpec[]
}

/**
 * 声明一个字。
 *
 * ⚠️ 参数顺序固定为「字, 拼音, 组词, 图」——`scripts/generate-voices.mjs`
 * 的 `loadHanzi()` 按这个顺序用正则扫，调换参数会让音频**静默地念错字**。
 * 那个正则还锚定行首，所以每次调用必须**独占一行**，别为了省行数把两个字写一行。
 */
function h(char: string, pinyin: string, word: string, emoji = ''): CardSpec {
  return { char, pinyin, word, emoji }
}

