/**
 * @file 识字 100 —— 一年级最先认的 100 个字，分 10 组
 * @layer data  静态内容，随 App 版本内置
 * @see src/domain/hanzi.ts  类型与 key 规则（朗读文本怎么拼在那边）
 * @see src/features/chinese/HanziWall.tsx  这面墙
 *
 * ## 选字依据
 *
 * 取自统编版语文一年级上册的识字课顺序（识字 1「天地人」→ 2「一二三四五上下」
 * → 3「口耳目手足站坐」→ 4「日月水火山石田禾」→ 5「对韵歌」），
 * 并按《义务教育语文课程标准》附录「识字、写字教学基本字表」的原则补足到 100：
 * **构形简单、重现率高、多数能作为其他字的结构成分**。
 *
 * 后五组（家人 / 动物 / 学习用品 / 动作 / 颜色）不是课本的分课，
 * 而是按**孩子能指得出来的东西**重新归的类——这一页是先于入学玩的，
 * 按课次分组对还没上学的孩子没有意义，按「这些都是我家里人」才有。
 *
 * ## ⚠️ 组词不是装饰，是朗读的一部分
 *
 * 每个字念出来是「天。蓝天的天。」——组词嵌在句子中间。所以 `word` 必须：
 *
 * 1. **能锁死多音字的读音** ——「地」单念可能读成助词 de，
 *    放进「大地的地」就只能是 dì。「长短的长」「多少的少」「你好的好」同理。
 *    这三个字如果组词换成别的，读音就可能翻车。
 * 2. **孩子听得懂** —— 组词里的另一个字要么已在这 100 个里，要么是她天天听的词。
 *
 * ## emoji 宁缺毋滥
 *
 * 与英语词表同一条规矩（见 englishWords.ts 文件头）：**认不出的图会把认字变成猜谜**。
 * 「大」「多」「来」「去」这类字没有干净的图，一律留空——
 * 卡片只显示字、拼音和组词，那比一张要猜的图干净。
 */

import type { HanziCard } from '@/domain/hanzi'

/** 一组识字卡 */
export interface HanziGroup {
  id: string
  /** 组名，给家长看的标签。孩子认的是这一组的图标与字本身 */
  name: string
  emoji: string
  cards: readonly HanziCard[]
}

/** 组内一个字的原始声明。`groupId` 由 {@link HANZI_GROUPS} 组装时补上 */
type CardSpec = Omit<HanziCard, 'groupId'>

/**
 * 声明一个字。
 *
 * ⚠️ 参数顺序固定为「字, 拼音, 组词, 图」——`scripts/generate-voices.mjs`
 * 的 `loadHanzi()` 按这个顺序用正则扫，调换参数会让音频**静默地念错字**。
 */
function h(char: string, pinyin: string, word: string, emoji = ''): CardSpec {
  return { char, pinyin, word, emoji }
}

